        [Header("Race setup")]
        [SerializeField] RouteCard[] routeCards;
        [SerializeField] Text lapsValue, opponentsValue, setupSummary;
        [SerializeField] Button lapsMinus, lapsPlus, oppMinus, oppPlus, startButton;

        [Header("Pools")]
        [SerializeField] InputField poolName, poolFee, poolStart;
        [SerializeField] Text poolLapsValue, poolRouteValue;
        [SerializeField] Button poolLapsMinus, poolLapsPlus, poolRouteMinus, poolRoutePlus, createPool, poolsPrev, poolsNext, resetSample;
