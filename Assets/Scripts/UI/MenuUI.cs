        /// <summary>Called by the editor scene builder.</summary>
        public void Configure(Transform showroomTurntable, RaceAudio audio)
        {
            turntable = showroomTurntable;
            menuAudio = audio;
        }

        // ================================================================== Runtime

        void Start()
        {
            cars = CarCatalog.Current;
            routes = RouteCatalog.Current;
            if (canvas == null) Build(cars != null ? cars.Count : 5, routes != null ? routes.Count : 4, cars != null ? cars.paintPalette.Length : 10);
            if (FindFirstObjectByType<EventSystem>() == null) new GameObject("EventSystem", typeof(EventSystem), typeof(StandaloneInputModule));
            Time.timeScale = 1f;
            LocalDataStore.Load();

            setup = RaceSession.HasSetup ? RaceSession.Setup : RaceSetup.Default;
            setup.carIndex = Mathf.Clamp(PlayerPrefs.GetInt("thegameio.car", setup.carIndex), 0, cars.Count - 1);
            colourIndex = Mathf.Clamp(PlayerPrefs.GetInt("thegameio.colour", 0), 0, cars.paintPalette.Length - 1);
            setup.paintColour = cars.paintPalette[colourIndex];
            setup.poolId = "";
            setup = setup.Normalised(cars.Count);

            Wire();
            RefreshGarage();
            SpawnShowroomCar();

            if (!RaceSession.SplashShown) StartCoroutine(SplashRoutine());
            else Show(RaceSession.ReturnScreen);
        }

        void Wire()
        {
            for (int i = 0; i < navButtons.Length; i++)
            {
                var screen = (MenuScreen)(i + 1);
                navButtons[i].onClick.AddListener(() => { Click(); Show(screen); });
            }
            if (graphicsButton != null)
            {
                graphicsButton.onClick.AddListener(() => { Click(); QualityTiers.Set(QualityTiers.Next(QualityTiers.Current)); RefreshGraphicsButton(); });
                RefreshGraphicsButton();
            }
            quickRace.onClick.AddListener(() => { Click(); Show(MenuScreen.RaceSetup); });
            poolsButton.onClick.AddListener(() => { Click(); Show(MenuScreen.Pools); });
            garageButton.onClick.AddListener(() => { Click(); Show(MenuScreen.Garage); });
            leaderboardButton.onClick.AddListener(() => { Click(); Show(MenuScreen.Leaderboard); });
            quitButton.onClick.AddListener(() => { Click(); Application.Quit(); });

            for (int i = 0; i < carCards.Length; i++)
            {
                int index = i;
                carCards[i].button.onClick.AddListener(() => { Click(); SelectCar(index); });
            }
            for (int i = 0; i < swatches.Length; i++)
            {
                int index = i;
                swatches[i].targetGraphic.color = cars.paintPalette[i % cars.paintPalette.Length];
                swatches[i].onClick.AddListener(() => { Click(); SelectColour(index); });
            }
            garageContinue.onClick.AddListener(() => { Click(); Show(MenuScreen.RaceSetup); });

            for (int i = 0; i < routeCards.Length; i++)
            {
                int index = i;
                routeCards[i].button.onClick.AddListener(() => { Click(); setup.routeIndex = index; RefreshRaceSetup(); });
            }
            lapsMinus.onClick.AddListener(() => { Click(); setup.laps = RaceRules.ClampLaps(setup.laps - 1); RefreshRaceSetup(); });
            lapsPlus.onClick.AddListener(() => { Click(); setup.laps = RaceRules.ClampLaps(setup.laps + 1); RefreshRaceSetup(); });
            oppMinus.onClick.AddListener(() => { Click(); setup.opponents = RaceRules.ClampOpponents(setup.opponents - 1); RefreshRaceSetup(); });
            oppPlus.onClick.AddListener(() => { Click(); setup.opponents = RaceRules.ClampOpponents(setup.opponents + 1); RefreshRaceSetup(); });
            startButton.onClick.AddListener(() => { Click(); StartQuickRace(); });

            poolLapsMinus.onClick.AddListener(() => { Click(); formLaps = RaceRules.ClampLaps(formLaps - 1); RefreshPoolForm(); });
            poolLapsPlus.onClick.AddListener(() => { Click(); formLaps = RaceRules.ClampLaps(formLaps + 1); RefreshPoolForm(); });
            poolRouteMinus.onClick.AddListener(() => { Click(); formRoute = (formRoute + RaceRules.RouteCount - 1) % RaceRules.RouteCount; RefreshPoolForm(); });
            poolRoutePlus.onClick.AddListener(() => { Click(); formRoute = (formRoute + 1) % RaceRules.RouteCount; RefreshPoolForm(); });
            createPool.onClick.AddListener(() => { Click(); CreatePoolFromForm(); });
            poolsPrev.onClick.AddListener(() => { Click(); poolPage = Mathf.Max(0, poolPage - 1); RefreshPools(); });
            poolsNext.onClick.AddListener(() => { Click(); poolPage++; RefreshPools(); });
            resetSample.onClick.AddListener(() => { Click(); LocalDataStore.ResetToSample(); poolPage = 0; RefreshPools(); poolsMessage.text = "Sample pools and leaderboard restored."; });
            for (int i = 0; i < poolCards.Length; i++)
            {
                int slot = i;
                poolCards[i].action.onClick.AddListener(() => { Click(); OnPoolAction(slot); });
            }
            joinConfirm.onClick.AddListener(() => { Click(); ConfirmJoin(); });
            joinCancel.onClick.AddListener(() => { Click(); joinDialog.SetActive(false); pendingJoin = null; });

            for (int i = 0; i < lbTabs.Length; i++)
            {
                int view = i;
                lbTabs[i].onClick.AddListener(() => { Click(); lbView = view; RefreshLeaderboard(); });
            }
            lbPrev.onClick.AddListener(() => { Click(); lbPoolCursor--; RefreshLeaderboard(); });
            lbNext.onClick.AddListener(() => { Click(); lbPoolCursor++; RefreshLeaderboard(); });
        }

        void Click()
        {
            if (menuAudio != null) menuAudio.PlayClick();
            if (EventSystem.current != null) EventSystem.current.SetSelectedGameObject(null);
        }

        IEnumerator SplashRoutine()
        {
            RaceSession.SplashShown = true;
            Show(MenuScreen.Main);
            splash.SetActive(true);
            splashGroup.alpha = 1f;
            float t = 0f;
            while (t < 2.2f && !Input.anyKeyDown && !Input.GetMouseButtonDown(0)) { t += Time.unscaledDeltaTime; yield return null; }
            for (float a = 1f; a > 0f; a -= Time.unscaledDeltaTime / 0.4f) { splashGroup.alpha = a; yield return null; }
            splash.SetActive(false);
        }

        public void Show(MenuScreen screen)
        {
            main.SetActive(screen == MenuScreen.Main);
            garage.SetActive(screen == MenuScreen.Garage);
            raceSetup.SetActive(screen == MenuScreen.RaceSetup);
            pools.SetActive(screen == MenuScreen.Pools);
            leaderboard.SetActive(screen == MenuScreen.Leaderboard);
            header.SetActive(true);
            joinDialog.SetActive(false);
            for (int i = 0; i < navButtons.Length; i++)
                navButtons[i].targetGraphic.color = (int)screen == i + 1 ? UIFactory.WithAlpha(UIFactory.Accent, 0.9f) : UIFactory.WithAlpha(Color.white, 0.06f);
            for (int i = 0; i < navButtons.Length; i++)
                UIFactory.ButtonText(navButtons[i]).color = (int)screen == i + 1 ? BrandConfig.Current.background : BrandConfig.Current.text;
            if (turntable != null) turntable.gameObject.SetActive(screen == MenuScreen.Main || screen == MenuScreen.Garage);
            switch (screen)
            {
                case MenuScreen.Main: RefreshMain(); break;
                case MenuScreen.Garage: RefreshGarage(); break;
                case MenuScreen.RaceSetup: RefreshRaceSetup(); break;
                case MenuScreen.Pools: RefreshPoolForm(); RefreshPools(); break;
                case MenuScreen.Leaderboard: RefreshLeaderboard(); break;
            }
        }

        void Update()
        {
            if (turntable != null) turntable.Rotate(0f, 14f * Time.unscaledDeltaTime, 0f, Space.World);
        }

        // ------------------------------------------------------------------ Garage

        public void SelectCar(int index)
        {
            setup.carIndex = cars != null && cars.Count > 0 ? Mathf.Clamp(index, 0, cars.Count - 1) : index;
            PlayerPrefs.SetInt("thegameio.car", setup.carIndex);
            RefreshGarage();
            SpawnShowroomCar();
        }

        public void SelectColour(int index)
        {
            colourIndex = index;
            setup.paintColour = cars.paintPalette[index];
            PlayerPrefs.SetInt("thegameio.colour", index);
            if (showroomCar != null) showroomCar.GetComponent<CarColourCustomizer>().SetColour(setup.paintColour);
            RefreshGarage();
        }

        void SpawnShowroomCar()
        {
            if (turntable == null || cars == null) return;
            if (showroomCar != null) Destroy(showroomCar);
            var entry = cars.Get(setup.carIndex);
            showroomCar = Instantiate(entry.prefab, turntable);
            showroomCar.transform.localPosition = Vector3.zero;
            showroomCar.transform.localRotation = Quaternion.identity;
            foreach (var b in showroomCar.GetComponents<Behaviour>())
                if (!(b is CarColourCustomizer) && !(b is AudioSource)) b.enabled = false;
            var rb = showroomCar.GetComponent<Rigidbody>();
            rb.isKinematic = true;
            rb.interpolation = RigidbodyInterpolation.None;
            showroomCar.GetComponent<AudioSource>().enabled = false;
            showroomCar.GetComponent<CarColourCustomizer>().SetColour(setup.paintColour);
            // The showroom probe is scripted: re-render it so the floor and walls reflect this car.
            var showroomProbe = FindFirstObjectByType<ReflectionProbe>();
            if (showroomProbe != null && showroomProbe.refreshMode == UnityEngine.Rendering.ReflectionProbeRefreshMode.ViaScripting) showroomProbe.RenderProbe();
        }

        void RefreshMain()
        {
            var e = cars.Get(setup.carIndex);
            selectedCarText.text = $"<color=#{BrandConfig.Hex(UIFactory.MutedText)}>SELECTED CAR</color>\n<size=34><b>{e.DisplayName}</b></size>\n{e.category}";
        }

        void RefreshGarage()
        {
            if (cars == null) return;
            var brand = BrandConfig.Current;
            for (int i = 0; i < carCards.Length; i++)
            {
                var card = carCards[i];
                bool has = i < cars.Count;
                card.root.SetActive(has);
                if (!has) continue;
                var e = cars.Get(i);
                bool selected = i == setup.carIndex;
                card.frame.color = selected ? brand.primary : UIFactory.WithAlpha(Color.white, 0.08f);
                card.disc.color = selected ? brand.accentRed : brand.panelLight;
                card.title.text = e.category;
                var icon = string.IsNullOrEmpty(e.icon) ? null : Resources.Load<Sprite>(e.icon);
                if (icon != null) card.icon.sprite = icon;
                card.desc.text = e.description;
                card.model.text = e.DisplayName;
                card.numbers.text = $"{Mathf.RoundToInt(e.topSpeedKmh)} km/h   ·   0-100 {e.zeroTo100:0.0} s   ·   grip {e.handlingIndex:0}";
                UIFactory.SetStatBar(card.speed, e.speedBar);
                UIFactory.SetStatBar(card.accel, e.accelBar);
                UIFactory.SetStatBar(card.handling, e.handlingBar);
            }
            for (int i = 0; i < swatchFrames.Length; i++)
                swatchFrames[i].color = i == colourIndex ? Color.white : UIFactory.WithAlpha(Color.white, 0f);
        }

        // ------------------------------------------------------------------ Quick race

        void RefreshRaceSetup()
        {
            for (int i = 0; i < routeCards.Length; i++)
            {
                var card = routeCards[i];
                bool has = routes != null && i < routes.Count;
                card.root.SetActive(has);
                if (!has) continue;
                var r = routes.Get(i);
                bool selected = i == setup.routeIndex;
                card.frame.color = selected ? UIFactory.Accent : UIFactory.WithAlpha(Color.white, 0.08f);
                card.title.text = $"ROUTE {r.number}";
                card.name.text = r.name;
                card.info.text = $"{r.districts}\n{r.lengthMetres / 1000f:0.00} km lap   ·   par {RaceFormat.Time(r.parLapSeconds)}";
                card.map.sprite = r.minimap;
                card.map.enabled = r.minimap != null;
            }
            lapsValue.text = setup.laps.ToString();
            opponentsValue.text = setup.opponents.ToString();
            var car = cars.Get(setup.carIndex);
            var route = routes.Get(setup.routeIndex);
            setupSummary.text = $"{car.DisplayName} ({car.category})   ·   Route {route.number} {route.name}   ·   {setup.laps} laps   ·   {setup.opponents + 1} cars on the grid";
        }

        public void StartQuickRace()
        {
            setup.poolId = "";
            RaceSession.Setup = setup.Normalised(cars.Count);
            RaceSession.HasSetup = true;
            RaceSession.OpponentNames = new string[0];
            RaceSession.PlayerGridSlot = -1;
            RaceSession.ReturnScreen = MenuScreen.RaceSetup;
            var r = routes.Get(setup.routeIndex);
            SceneLoader.Load(r.sceneName, $"Route {r.number}  ·  {r.name}");
        }

        // ------------------------------------------------------------------ Pools

        void RefreshPoolForm()
        {
            if (string.IsNullOrEmpty(poolName.text)) poolName.text = LocalDataStore.NextPoolName;
            if (string.IsNullOrEmpty(poolStart.text)) poolStart.text = DateTime.Now.AddMinutes(30).ToString("yyyy-MM-dd HH:mm", CultureInfo.InvariantCulture);
            poolLapsValue.text = formLaps.ToString();
            var r = routes.Get(formRoute);
            poolRouteValue.text = $"Route {r.number}  ·  {r.name}";
        }

        void CreatePoolFromForm()
        {
            int fee = 0;
            if (!string.IsNullOrWhiteSpace(poolFee.text) && !int.TryParse(poolFee.text.Trim(), out fee))
            {
                poolsMessage.text = "Entry fee must be a whole number (coins). It is display-only in this sample.";
                return;
            }
            if (!DateTime.TryParseExact(poolStart.text.Trim(), "yyyy-MM-dd HH:mm", CultureInfo.InvariantCulture, DateTimeStyles.None, out var start))
            {
                poolsMessage.text = "Start time format: yyyy-MM-dd HH:mm";
                return;
            }
            var pool = LocalDataStore.CreatePool(poolName.text, fee, formLaps, formRoute, start);
            poolName.text = LocalDataStore.NextPoolName;
            poolsMessage.text = $"{pool.name} created  ·  Open  ·  0 / {pool.maxPlayers} joined.";
            poolPage = Mathf.Max(0, (LocalDataStore.Pools.Count - 1) / PoolsPerPage);
            RefreshPools();
        }

        void RefreshPools()
        {
            var brand = BrandConfig.Current;
            var all = LocalDataStore.Pools;
            int pages = Mathf.Max(1, Mathf.CeilToInt(all.Count / (float)PoolsPerPage));
            poolPage = Mathf.Clamp(poolPage, 0, pages - 1);
            poolsPage.text = $"{poolPage + 1} / {pages}";
            poolsPrev.interactable = poolPage > 0;
            poolsNext.interactable = poolPage < pages - 1;
            for (int c = 0; c < poolCards.Length; c++)
            {
                var card = poolCards[c];
                int index = poolPage * PoolsPerPage + c;
                bool has = index < all.Count;
                card.root.SetActive(has);
                if (!has) continue;
                var p = all[index];
                card.title.text = p.name;
                card.badge.text = p.status.ToString();
                card.badgeBg.color = p.status == PoolStatus.Open ? brand.open : p.status == PoolStatus.Full ? brand.full : p.status == PoolStatus.Racing ? brand.racing : brand.finished;
                for (int s = 0; s < card.seats.Length; s++)
                {
                    bool taken = s < p.players.Count;
                    bool beyond = s >= p.maxPlayers;
                    card.seats[s].gameObject.SetActive(!beyond);
                    card.seats[s].color = taken ? brand.panel : new Color(0.93f, 0.94f, 0.96f);
                    card.seatText[s].color = taken ? brand.text : brand.mutedText;
                    card.seatText[s].text = taken ? (p.players[s] == RaceSession.PlayerName ? "YOU" : "P" + (s + 1)) : "Open";
                }
                card.joined.text = $"{p.Joined} / {p.maxPlayers} joined";
                card.fee.text = p.entryFee > 0 ? $"Entry fee {p.entryFee} coins  ·  set by admin" : "Entry fee set by admin";
                var r = routes.Get(p.route);
                card.details.text = $"Route {r.number} {r.name}  ·  {p.laps} laps\nStarts {p.StartDateTime:dd MMM HH:mm}{(p.sample ? "  ·  sample" : "")}";
                bool alreadyIn = p.players.Contains(RaceSession.PlayerName);
                switch (p.status)
                {
                    case PoolStatus.Open:
                        card.action.interactable = true;
                        card.actionText.text = alreadyIn ? "RACE (JOINED)" : "JOIN POOL";
                        break;
                    case PoolStatus.Full:
                        card.action.interactable = alreadyIn;
                        card.actionText.text = alreadyIn ? "RACE (JOINED)" : "POOL FULL";
                        break;
                    case PoolStatus.Racing:
                        card.action.interactable = false;
                        card.actionText.text = "RACE IN PROGRESS";
                        break;
                    default:
                        card.action.interactable = true;
                        card.actionText.text = "VIEW RESULTS";
                        break;
                }
            }
        }

        void OnPoolAction(int cardIndex)
        {
            var all = LocalDataStore.Pools;
            int index = poolPage * PoolsPerPage + cardIndex;
            if (index >= all.Count) return;
            var p = all[index];
            if (p.status == PoolStatus.Finished)
            {
                lbView = 0;
                lbSelectPoolId = p.id;
                Show(MenuScreen.Leaderboard);
                return;
            }
            bool alreadyIn = p.players.Contains(RaceSession.PlayerName);
            if (!alreadyIn && !p.HasSeat) return;
            pendingJoin = p;
            var r = routes.Get(p.route);
            int seat = alreadyIn ? p.players.IndexOf(RaceSession.PlayerName) + 1 : p.Joined + 1;
            joinTitle.text = alreadyIn ? $"RACE {p.name.ToUpperInvariant()}" : $"JOIN {p.name.ToUpperInvariant()}";
            joinBody.text =
                $"Route {r.number}  ·  {r.name}\n{p.laps} laps  ·  seat P{seat} of {p.maxPlayers}  ·  {p.Joined + (alreadyIn ? 0 : 1)} racers\n\n" +
                $"Entry fee: {(p.entryFee > 0 ? p.entryFee + " coins" : "set by admin")}\n" +
                $"<color=#{BrandConfig.Hex(UIFactory.MutedText)}>Not charged - payment, wallet and prizes are outside this sample (PPT slide 13). " +
                "In the full game the race starts when the pool is full or at its scheduled time; this sample starts it now with the joined racers (AI-driven).</color>";
            joinDialog.SetActive(true);
        }

        /// <summary>Joins a pool and starts its race (what the JOIN & RACE dialog does).</summary>
        public void JoinPool(PoolRecord pool)
        {
            pendingJoin = pool;
            ConfirmJoin();
        }

        public void SelectRoute(int index) { setup.routeIndex = RaceRules.ClampRoute(index); RefreshRaceSetup(); }
        public void SetLaps(int laps) { setup.laps = RaceRules.ClampLaps(laps); RefreshRaceSetup(); }
        public RaceSetup CurrentSetup => setup;
        public bool SplashVisible => splash != null && splash.activeSelf;

        void ConfirmJoin()
        {
            var p = pendingJoin;
            joinDialog.SetActive(false);
            if (p == null) return;
            if (!p.players.Contains(RaceSession.PlayerName) && !LocalDataStore.Join(p, RaceSession.PlayerName))
            {
                poolsMessage.text = $"{p.name} is no longer open.";
                RefreshPools();
                return;
            }
            setup.poolId = p.id;
            setup.routeIndex = p.route;
            setup.laps = p.laps;
            setup.opponents = p.players.Count - 1;
            RaceSession.Setup = setup.Normalised(cars.Count);
            RaceSession.HasSetup = true;
            RaceSession.OpponentNames = p.players.Where(n => n != RaceSession.PlayerName).ToArray();
            RaceSession.PlayerGridSlot = p.players.IndexOf(RaceSession.PlayerName);
            RaceSession.ReturnScreen = MenuScreen.Pools;
            var r = routes.Get(p.route);
            SceneLoader.Load(r.sceneName, $"{p.name}  ·  Route {r.number} {r.name}");
        }

        // ------------------------------------------------------------------ Leaderboard

        void RefreshLeaderboard()
        {
            var brand = BrandConfig.Current;
            for (int i = 0; i < lbTabs.Length; i++)
            {
                lbTabs[i].targetGraphic.color = i == lbView ? brand.primary : brand.panelLight;
                UIFactory.ButtonText(lbTabs[i]).color = i == lbView ? brand.background : brand.text;
            }
            var poolsWithResults = LocalDataStore.Pools.Where(p => LocalDataStore.PoolStandings(p.id).Count > 0).ToList();
            bool poolView = lbView == 0;
            lbPrev.gameObject.SetActive(poolView);
            lbNext.gameObject.SetActive(poolView);
            lbPoolName.gameObject.SetActive(poolView);

            foreach (var row in lbRows) row.root.SetActive(false);
            if (poolView)
            {
                if (poolsWithResults.Count == 0)
                {
                    lbTitle.text = "Leaderboard";
                    lbPoolName.text = "No pool results yet";
                    lbFooter.text = "";
                    return;
                }
                if (!string.IsNullOrEmpty(lbSelectPoolId))
                {
                    int found = poolsWithResults.FindIndex(p => p.id == lbSelectPoolId);
                    if (found >= 0) lbPoolCursor = found;
                    lbSelectPoolId = null;
                }
                lbPoolCursor = ((lbPoolCursor % poolsWithResults.Count) + poolsWithResults.Count) % poolsWithResults.Count;
                var pool = poolsWithResults[lbPoolCursor];
                lbTitle.text = $"Leaderboard  ·  {pool.name}";
                lbPoolName.text = $"{pool.name}  ·  {pool.status}";
                lbHeader1.text = "BEST LAP"; lbHeader2.text = "TOTAL TIME"; lbHeader3.text = "STATUS";
                var standings = LocalDataStore.PoolStandings(pool.id);
                for (int i = 0; i < lbRows.Length && i < standings.Count; i++)
                {
                    var r = standings[i];
                    FillRow(lbRows[i], r.dnf ? 0 : r.rank, r.player + (r.isLocalPlayer ? "" : r.sample ? "  <size=14><color=#888>sample</color></size>" : ""), r.isLocalPlayer,
                        RaceFormat.Time(r.bestLap), r.dnf ? "DNF" : RaceFormat.Time(r.totalTime), r.dnf ? "DNF" : "Finished");
                }
                lbFooter.text = $"All {standings.Count} pool players listed  ·  ranked by lowest total time, tie-break best lap then earliest finish";
            }
            else
            {
                var period = lbView == 1 ? LocalDataStore.Period.Daily : lbView == 2 ? LocalDataStore.Period.Weekly : LocalDataStore.Period.AllTime;
                string label = lbView == 1 ? "Today" : lbView == 2 ? "This week" : "All time";
                lbTitle.text = $"Leaderboard  ·  {label}";
                lbHeader1.text = "WINS"; lbHeader2.text = "BEST LAP"; lbHeader3.text = "RACES";
                var totals = LocalDataStore.Aggregate(period, DateTime.Now);
                for (int i = 0; i < lbRows.Length && i < totals.Count; i++)
                {
                    var t = totals[i];
                    FillRow(lbRows[i], i + 1, t.player + (t.sample ? "  <size=14><color=#888>sample</color></size>" : ""), t.isLocalPlayer,
                        $"{t.wins}  <size=14><color=#888>{t.seconds}x2nd {t.thirds}x3rd</color></size>", RaceFormat.Time(t.bestLap), t.races.ToString());
                }
                lbFooter.text = totals.Count == 0 ? "No races in this period yet." :
                    $"{totals.Count} players  ·  ranked by winner trophies, then 2nd/3rd places, then best lap" + (totals.Count > lbRows.Length ? $"  ·  top {lbRows.Length} shown" : "");
            }
        }

        void FillRow(LeaderRow row, int rank, string player, bool isPlayer, string c1, string c2, string c3)
        {
            var brand = BrandConfig.Current;
            row.root.SetActive(true);
            bool podium = rank >= 1 && rank <= 3;
            row.bg.color = podium ? UIFactory.WithAlpha(brand.panelLight, 1f) : isPlayer ? UIFactory.WithAlpha(brand.primary, 0.18f) : UIFactory.WithAlpha(Color.white, 0f);
            row.trophy.gameObject.SetActive(podium);
            if (podium) row.trophy.color = UIFactory.TrophyColour(rank);
            row.rank.text = podium ? "" : rank == 0 ? "-" : rank.ToString();
            row.player.text = isPlayer ? $"<b>{player}</b>  <size=14><color=#{BrandConfig.Hex(brand.primary)}>YOU</color></size>" : player;
            row.player.fontStyle = podium ? FontStyle.Bold : FontStyle.Normal;
            row.c1.text = c1;
            row.c2.text = c2;
            row.c2.color = rank == 1 ? brand.primary : brand.text;
            row.c3.text = c3;
        }

