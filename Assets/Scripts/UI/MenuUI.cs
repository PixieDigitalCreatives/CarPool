        {
            public GameObject root; public Image frame, map; public Text title, name, info; public Button button;
        }
        [Serializable] public class PoolCard
        {
            public GameObject root; public Text title, badge, joined, fee, details; public Image badgeBg; public Button action; public Text actionText;
            public Image[] seats; public Text[] seatText;
        }
