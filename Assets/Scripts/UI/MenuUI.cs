        [SerializeField] CanvasGroup splashGroup;
        [SerializeField] Button[] navButtons;
        [SerializeField] Button graphicsButton;

        [Header("Main")]
        [SerializeField] Button quickRace, poolsButton, garageButton, leaderboardButton, quitButton;
